#!/usr/bin/env python3
"""Generate RTL constants and documentation from ``isa/isa.yaml``.

Usage::

    python tools/gen_isa.py            # write src/isa_pkg.sv and docs/isa.md
    python tools/gen_isa.py --check    # fail if generated files are stale

The generated files are committed so that the RTL build and the docs build do
not need to run Python first. CI runs ``--check`` to catch drift.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "sw"))

from janus.isa import ISA, default_isa  # noqa: E402

SV_PATH = REPO / "src" / "isa_pkg.sv"
MD_PATH = REPO / "docs" / "isa.md"


def _sv_hex(value: int, width_bits: int) -> str:
    digits = (width_bits + 3) // 4
    return f"{width_bits}'h{value:0{digits}x}"


def generate_sv(isa: ISA) -> str:
    lines: list[str] = []
    lines.append("// Generated by tools/gen_isa.py from isa/isa.yaml. Do not edit.")
    lines.append(f"// ISA version {isa.version}")
    lines.append("`ifndef JANUS_ISA_PKG_SV")
    lines.append("`define JANUS_ISA_PKG_SV")
    lines.append("")
    lines.append("package isa_pkg;")
    lines.append("")
    lines.append(f"  localparam int unsigned XLEN = {isa.word_bits};")
    lines.append(f"  localparam int unsigned ADDR_BITS = {isa.address_bits};")
    lines.append(f"  localparam int unsigned REG_COUNT = {isa.reg_count};")
    lines.append(f"  localparam int unsigned CONTEXT_COUNT = {isa.context_count};")
    lines.append(f"  localparam logic [3:0] REG_ZERO = 4'd{isa.reg_zero};")
    lines.append(f"  localparam logic [3:0] REG_LINK = 4'd{isa.reg_link};")
    lines.append("")

    lines.append("  // Instruction opcodes")
    for insn in sorted(isa.instructions.values(), key=lambda item: item.opcode):
        lines.append(f"  localparam logic [7:0] OP_{insn.name} = {_sv_hex(insn.opcode, 8)};")
    lines.append("")

    lines.append("  // Field positions, per format. Field order matches isa.yaml.")
    for fmt_name, fmt in isa.formats.items():
        lines.append(f"  // format {fmt_name}")
        for field_name, (msb, lsb) in fmt.fields.items():
            prefix = f"FMT_{fmt_name}_{field_name.upper()}"
            lines.append(f"  localparam int unsigned {prefix}_MSB = {msb};")
            lines.append(f"  localparam int unsigned {prefix}_LSB = {lsb};")
    lines.append("")

    mem = isa.memory
    io = mem["io"]
    lines.append("  // Memory map")
    lines.append(f"  localparam logic [31:0] IMEM_WORDS = 32'd{mem['instruction']['size_words']};")
    lines.append(f"  localparam logic [31:0] DMEM_BYTES = 32'd{mem['data']['size_bytes']};")
    lines.append(f"  localparam logic [31:0] IO_BASE = {_sv_hex(int(io['base']), 32)};")
    lines.append(f"  localparam logic [31:0] IO_BYTES = 32'd{io.get('size_bytes', 256)};")
    for name, entry in isa.io.items():
        lines.append(f"  localparam logic [31:0] IO_{name} = {_sv_hex(int(entry['address']), 32)};")
    lines.append("")

    lines.append("  // Pin masks")
    lines.append("  localparam logic [23:0] PIN_INPUT_MASK = 24'hFF00FF;")
    lines.append("  localparam logic [23:0] PIN_OUTPUT_MASK = 24'hFFFF00;")
    lines.append("  localparam logic [23:0] PIN_BIDIR_MASK = 24'hFF0000;")
    lines.append("")
    lines.append("  // Sign-extend the low bits of a value to XLEN.")
    lines.append("  function automatic logic [31:0] sign_extend(input logic [31:0] value, input int unsigned bits);")
    lines.append("    logic [31:0] shifted;")
    lines.append("    begin")
    lines.append("      shifted = value << (32 - bits);")
    lines.append("      sign_extend = $signed(shifted) >>> (32 - bits);")
    lines.append("    end")
    lines.append("  endfunction")
    lines.append("")
    lines.append("endpackage")
    lines.append("")
    lines.append("`endif")
    lines.append("")
    return "\n".join(lines)


def _syntax(insn) -> str:
    parts: list[str] = []
    index = 0
    while index < len(insn.operands):
        op = insn.operands[index]
        if op.kind == "memoff":
            base = insn.operands[index + 1]
            parts.append(f"offset({base.field})")
            index += 2
            continue
        if op.kind == "membase":
            index += 1
            continue
        if op.kind == "label":
            parts.append("target")
        else:
            parts.append(op.field)
        index += 1
    return f"{insn.name.lower()} " + ", ".join(parts) if parts else insn.name.lower()


def generate_md(isa: ISA) -> str:
    out: list[str] = []
    out.append(f"# JANUS ISA reference (v{isa.version})")
    out.append("")
    out.append(
        "> Generated from [`isa/isa.yaml`](../isa/isa.yaml) by `tools/gen_isa.py`. "
        "Do not edit by hand."
    )
    out.append("")
    out.append(isa.raw.get("description", "").strip())
    out.append("")

    out.append("## Registers")
    out.append("")
    out.append(
        f"{isa.reg_count} general-purpose {isa.reg_width}-bit registers per context. "
        f"`{isa.reg_names[isa.reg_zero]}` always reads as zero; writes to it are discarded. "
        f"`{isa.reg_names[isa.reg_link]}` is the default link register for `CALL`."
    )
    out.append("")
    out.append("| Register | Name | Notes |")
    out.append("| --- | --- | --- |")
    for index, name in enumerate(isa.reg_names):
        note = ""
        if index == isa.reg_zero:
            note = "hardwired zero"
        elif index == isa.reg_link:
            note = "link register by convention"
        out.append(f"| `{name}` | r{index} | {note} |")
    out.append("")

    out.append("## Contexts and timing")
    out.append("")
    out.append(isa.raw["contexts"]["schedule"].strip())
    out.append("")
    out.append(
        "The global cycle counter is readable at `CYCLE`. `WAITREL rs` stalls the issuing "
        "context until the counter reaches the issue cycle plus `rs`; `WAITABS rs` waits for "
        "an absolute cycle; `WAITPIN rs1, rs2` waits for an edge on the pins selected by "
        "`rs1`, with an optional absolute timeout in `rs2` (zero means no timeout)."
    )
    out.append("")

    out.append("## Instruction formats")
    out.append("")
    out.append("| Format | Fields (MSB:LSB) |")
    out.append("| --- | --- |")
    for fmt_name, fmt in isa.formats.items():
        fields = ", ".join(f"`{name}` {msb}:{lsb}" for name, (msb, lsb) in fmt.fields.items())
        out.append(f"| `{fmt_name}` | {fields} |")
    out.append("")

    out.append("## Instructions")
    out.append("")
    out.append("| Mnemonic | Opcode | Format | Syntax | Semantics |")
    out.append("| --- | --- | --- | --- | --- |")
    for insn in sorted(isa.instructions.values(), key=lambda item: item.opcode):
        semantics = insn.semantics.strip().replace("|", "\\|")
        out.append(
            f"| `{insn.name}` | `0x{insn.opcode:02X}` | `{insn.format}` | "
            f"`{_syntax(insn)}` | {semantics} |"
        )
    out.append("")

    out.append("## Pseudo-instructions")
    out.append("")
    out.append("| Alias | Operands | Expands to |")
    out.append("| --- | --- | --- |")
    for alias in isa.aliases.values():
        expansion = " ; ".join(f"`{line}`" for line in alias.expands)
        out.append(f"| `{alias.name}` | {alias.operands} | {expansion} |")
    out.append("")

    out.append("## Memory map")
    out.append("")
    out.append("| Region | Base | Size | Notes |")
    out.append("| --- | --- | --- | --- |")
    out.append(
        f"| Instruction | `0x{int(isa.memory['instruction']['base']):08X}` | "
        f"{isa.memory['instruction']['size_words']} words | {isa.memory['instruction'].get('note', '')} |"
    )
    out.append(
        f"| Data | `0x{int(isa.memory['data']['base']):08X}` | "
        f"{isa.memory['data']['size_bytes']} bytes | {isa.memory['data'].get('note', '')} |"
    )
    out.append(
        f"| I/O | `0x{int(isa.memory['io']['base']):08X}` | "
        f"{isa.memory['io'].get('size_bytes', 256)} bytes | memory-mapped registers |"
    )
    out.append("")
    out.append("### I/O registers")
    out.append("")
    out.append("| Name | Address | Access | Description |")
    out.append("| --- | --- | --- | --- |")
    for name, entry in isa.io.items():
        out.append(
            f"| `{name}` | `0x{int(entry['address']):08X}` | {entry['access']} | {entry['desc']} |"
        )
    out.append("")

    out.append("## Pin map")
    out.append("")
    out.append("| Pin | Source | Direction |")
    out.append("| --- | --- | --- |")
    for pin in isa.raw.get("pins", []):
        out.append(f"| {pin['index']} | `{pin['source']}` | {pin['direction']} |")
    out.append("")

    boot = isa.raw.get("boot", {})
    if boot:
        out.append("## Boot protocol")
        out.append("")
        out.append(
            f"On reset the bootloader listens on pins {boot['uart_pins'][0]} and "
            f"{boot['uart_pins'][1]} (`uio[0]` and `uio[1]`) for a little-endian image "
            f"introduced by the magic value `0x{int(boot['magic']):X}`."
        )
        out.append("")
        out.append(boot.get("note", "").strip())
        out.append("")

    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files are current")
    args = parser.parse_args(argv)

    isa = default_isa()
    sv = generate_sv(isa)
    md = generate_md(isa)

    if args.check:
        stale = []
        for path, content in ((SV_PATH, sv), (MD_PATH, md)):
            actual = path.read_text(encoding="utf-8") if path.exists() else ""
            if actual != content:
                stale.append(path)
        if stale:
            for path in stale:
                print(f"stale: {path}", file=sys.stderr)
            print("run python tools/gen_isa.py", file=sys.stderr)
            return 1
        print("generated ISA files are current")
        return 0

    SV_PATH.parent.mkdir(parents=True, exist_ok=True)
    MD_PATH.parent.mkdir(parents=True, exist_ok=True)
    SV_PATH.write_text(sv, encoding="utf-8")
    MD_PATH.write_text(md, encoding="utf-8")
    print(f"wrote {SV_PATH.relative_to(REPO)}")
    print(f"wrote {MD_PATH.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
